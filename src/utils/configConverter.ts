/**
 * 将节点转换为 Shadowrocket 配置格式（链接形式）
 */
export const convertToShadowrocket = (nodes: ProxyNode[]): string => {
  if (!nodes || nodes.length === 0) {
    return '# No proxies found'
  }
  
  // Base64 编码辅助函数，支持 Unicode
  const base64Encode = (str: string): string => {
    try {
      return btoa(unescape(encodeURIComponent(str)))
    } catch (error) {
      console.error('Base64 encoding failed:', error)
      throw error
    }
  }
  
  const links: string[] = []
  
  nodes.forEach(node => {
    if (!node || !node.server || !node.port) return
    
    let link = ''
    
    switch (node.type) {
      case 'ss':
        if (!node.password || !node.method) return
        try {
          const ssContent = `${node.method}:${node.password}@${node.server}:${node.port}`
          link = `ss://${base64Encode(ssContent)}#${encodeURIComponent(sanitizeName(node.name))}`
        } catch {
          link = `# Failed to encode SS link: ${sanitizeName(node.name)}`
        }
        break
      case 'vmess':
        if (!node.uuid) return
        try {
          const vmessObj = {
            v: '2',
            ps: sanitizeName(node.name),
            add: node.server,
            port: node.port,
            id: node.uuid,
            aid: node.alterId || 0,
            scy: node.cipher || 'auto',
            net: node.network || 'tcp',
            path: node.path || '',
            sni: node.sni || ''
          }
          link = `vmess://${base64Encode(JSON.stringify(vmessObj))}`
        } catch {
          link = `# Failed to encode VMess link: ${sanitizeName(node.name)}`
        }
        break
      case 'trojan':
        if (!node.password) return
        link = `trojan://${node.password}@${node.server}:${node.port}#${encodeURIComponent(sanitizeName(node.name))}`
        break
      case 'ssr':
        link = `# SSR 链接不支持直接转换为 Shadowrocket 格式: ${sanitizeName(node.name)}`
        break
      default:
        link = `# ${sanitizeName(node.name)} (不支持的类型: ${node.type})`
    }
    
    if (link) links.push(link)
  })

  if (links.length === 0) {
    return '# No valid proxies to convert'
  }
  
  return links.join('\n')
}

/**
 * 将节点转换为 Sing-box 配置格式
 */
export const convertToSingbox = (nodes: ProxyNode[]): string => {
  if (!nodes || nodes.length === 0) {
    return JSON.stringify({ error: 'No proxies found' }, null, 2)
  }
  
  const outbounds: any[] = []
  const outboundTags: string[] = []
  
  nodes.forEach(node => {
    if (!node || !node.server || !node.port) return
    
    let outbound: any = {
      type: node.type,
      tag: sanitizeName(node.name),
      server: node.server,
      server_port: node.port
    }
    
    switch (node.type) {
      case 'ss':
        if (!node.password || !node.method) return
        outbound.cipher = node.method
        outbound.password = node.password
        break
      case 'vmess':
        if (!node.uuid) return
        outbound.uuid = node.uuid
        outbound.alter_id = node.alterId || 0
        outbound.security = node.security || 'auto'
        if (node.network && node.network !== 'tcp') {
          outbound.transport = {
            type: node.network === 'ws' ? 'ws' : node.network,
            path: node.path || '/'
          }
        }
        if (node.sni) {
          outbound.tls = {
            enabled: true,
            server_name: node.sni,
            insecure: false
          }
        }
        break
      case 'trojan':
        if (!node.password) return
        outbound.password = node.password
        if (node.sni) {
          outbound.tls = {
            enabled: true,
            server_name: node.sni,
            insecure: false
          }
        }
        break
      case 'ssr':
        // Sing-box 不原生支持 SSR
        return
      default:
        return
    }
    
    outbounds.push(outbound)
    outboundTags.push(sanitizeName(node.name))
  })

  if (outbounds.length === 0) {
    return JSON.stringify({ error: 'No valid proxies to convert' }, null, 2)
  }

  const config = {
    log: { level: 'info' },
    inbounds: [{ type: 'mixed', listen: '0.0.0.0', listen_port: 7890, tag: 'mixed-in' }],
    outbounds: [
      { type: 'direct', tag: 'direct' },
      ...outbounds,
      {
        type: 'selector',
        tag: '🚀 节点选择',
        outbounds: outboundTags
      }
    ],
    route: {
      rules: [{ inbound: ['mixed-in'], outbound: '🚀 节点选择' }]
    }
  }

  return JSON.stringify(config, null, 2)
}

/**
 * 将节点转换为 V2Ray 链接格式
 */
export const convertToV2Ray = (nodes: ProxyNode[]): string => {
  if (!nodes || nodes.length === 0) {
    return '# No proxies found'
  }
  
  const links: string[] = []
  
  // Base64 编码辅助函数，支持 Unicode
  const base64Encode = (str: string): string => {
    try {
      // 使用 encodeURIComponent 和 unescape 处理 Unicode
      return btoa(unescape(encodeURIComponent(str)))
    } catch (error) {
      console.error('Base64 encoding failed:', error)
      throw error
    }
  }
  
  nodes.forEach(node => {
    if (!node || !node.server || !node.port) return
    
    let link = ''
    
    switch (node.type) {
      case 'ss':
        if (!node.password || !node.method) return
        try {
          const ssContent = `${node.method}:${node.password}@${node.server}:${node.port}`
          link = `ss://${base64Encode(ssContent)}#${encodeURIComponent(sanitizeName(node.name))}`
        } catch {
          link = `# Failed to encode SS link: ${sanitizeName(node.name)}`
        }
        break
      case 'vmess':
        if (!node.uuid) return
        try {
          const vmessObj = {
            v: '2',
            ps: sanitizeName(node.name),
            add: node.server,
            port: String(node.port),
            id: node.uuid,
            aid: String(node.alterId || 0),
            net: node.network || 'tcp',
            type: 'none',
            host: '',
            path: node.path || '',
            tls: node.sni ? 'tls' : '',
            sni: node.sni || '',
            alpn: '',
            fp: ''
          }
          link = `vmess://${base64Encode(JSON.stringify(vmessObj))}`
        } catch {
          link = `# Failed to encode VMess link: ${sanitizeName(node.name)}`
        }
        break
      case 'trojan':
        if (!node.password) return
        link = `trojan://${node.password}@${node.server}:${node.port}#${encodeURIComponent(sanitizeName(node.name))}`
        break
      case 'ssr':
        // SSR 需要特殊编码
        try {
          const baseInfo = `${node.server}:${node.port}:origin:${node.method || 'aes-256-cfb'}:plain:${base64Encode(node.password || '')}/`
          const params = `obfsparam=&protoparam=&remarks=${base64Encode(encodeURIComponent(sanitizeName(node.name)))}&group=`
          link = `ssr://${base64Encode(baseInfo + '?' + params)}`
        } catch {
          link = `# Failed to encode SSR link: ${sanitizeName(node.name)}`
        }
        break
      default:
        link = `# ${sanitizeName(node.name)} (不支持的类型: ${node.type})`
    }
    
    if (link) links.push(link)
  })

  if (links.length === 0) {
    return '# No valid proxies to convert'
  }
  
  return links.join('\n')
}

/**
 * 根据目标格式转换节点
 */
export const convertToConfigFormat = (nodes: ProxyNode[], targetFormat: ConfigFormat): string => {
  switch (targetFormat) {
    case 'clash':
      return convertToClash(nodes)
    case 'surge':
      return convertToSurge(nodes)
    case 'quantumult':
      return convertToQuantumult(nodes)
    case 'quantumultX':
      return convertToQuantumultX(nodes)
    case 'shadowrocket':
      return convertToShadowrocket(nodes)
    case 'singbox':
      return convertToSingbox(nodes)
    case 'v2ray':
      return convertToV2Ray(nodes)
    default:
      return JSON.stringify(nodes, null, 2)
  }
}

/**
 * 清理节点名称（移除特殊字符）
 */
const sanitizeName = (name: string): string => {
  if (!name) return 'unnamed'
  // 移除危险字符，保留常用字符
  return name.replace(/["'`\\\[\]{}()<>|&;^$#!*?~]/g, '').trim()
}